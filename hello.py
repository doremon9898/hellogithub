# ตัวอย่างพื้นฐานการคำนวณใน Python

a = 10
b = 3

print('a =', a)
print('b =', b)
print('ผลบวก:', a + b)
print('ผลลบ:', a - b)
print('ผลคูณ:', a * b)
print('ผลหาร:', a / b)
print('เศษ:', a % b)

# ตัวอย่างแปลงค่า
x = 5
x = x + 2
print('x =', x)

# ตัวอย่างรับค่าจากผู้ใช้
num1 = int(input('กรอกตัวเลขตัวที่ 1: '))
num2 = int(input('กรอกตัวเลขตัวที่ 2: '))
print('ผลรวม:', num1 + num2)
